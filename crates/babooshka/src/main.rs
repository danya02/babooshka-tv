// ---------------------------------------------------------------------------
// CLI — only used to locate the config file
// ---------------------------------------------------------------------------

#[derive(clap::Parser, Debug)]
struct Cli {
    /// Path to the TOML configuration file
    #[clap(long, default_value = "/srv/babooshka-config.toml")]
    config: PathBuf,
}

// ---------------------------------------------------------------------------
// Configuration (loaded from TOML)
// ---------------------------------------------------------------------------

#[derive(Debug, serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct Config {
    /// File to save/restore playback state
    #[serde(default = "defaults::play_state")]
    play_state: PathBuf,

    /// JSON playlist file
    #[serde(default = "defaults::playlist")]
    playlist: PathBuf,

    #[serde(default)]
    gpio: GpioConfig,

    #[serde(default)]
    tv: TvConfig,

    #[serde(default)]
    hdmi: HdmiConfig,

    /// Path to the Unix socket for software switch overrides.
    /// Send `on\n` or `off\n` to simulate the switch changing state.
    /// Set to an empty string to disable.
    #[serde(default = "defaults::control_socket")]
    control_socket: PathBuf,

    /// Optional path to a JSON file mapping video paths to gain adjustments in dB.
    /// Generated by `playlistctl`.  Set to an empty string to disable.
    #[serde(default = "defaults::gain_db")]
    gain_db: PathBuf,

    /// Whether to actually apply the gains from `gain_db`.
    ///
    /// The map is loaded and logged either way, so a run can be checked against
    /// real playback before the gains take effect.  Off by default: applying an
    /// untrusted gain map would change the volume of every film at once.
    #[serde(default)]
    gain_enabled: bool,
}

#[derive(Debug, serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct GpioConfig {
    /// BCM pin number for the switch input (pull-up; to-ground = inactive)
    #[serde(default = "defaults::gpio_switch_pin")]
    switch_pin: u8,

    /// BCM pin number for the status LED output
    #[serde(default = "defaults::gpio_led_pin")]
    led_pin: u8,
}

impl Default for GpioConfig {
    fn default() -> Self {
        Self {
            switch_pin: defaults::gpio_switch_pin(),
            led_pin: defaults::gpio_led_pin(),
        }
    }
}

#[derive(Debug, serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct TvConfig {
    /// "smartplug", "cec", or "both"
    #[serde(default = "defaults::tv_control")]
    control: TvControlMode,

    /// Home Assistant base URL
    #[serde(default = "defaults::ha_url")]
    ha_url: String,

    /// Home Assistant long-lived access token
    ha_token: Option<String>,

    /// Home Assistant entity ID for the smart plug
    #[serde(default = "defaults::ha_entity")]
    ha_entity: String,
}

impl Default for TvConfig {
    fn default() -> Self {
        Self {
            control: defaults::tv_control(),
            ha_url: defaults::ha_url(),
            ha_token: None,
            ha_entity: defaults::ha_entity(),
        }
    }
}

#[derive(Debug, serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct HdmiConfig {
    /// "drm", "timeout", or "cec"
    #[serde(default = "defaults::hdmi_detect")]
    detect: HdmiDetectMode,

    /// Seconds to wait when using the "timeout" detection mode,
    /// or the fallback timeout for "cec" mode
    #[serde(default = "defaults::hdmi_timeout_secs")]
    timeout_secs: u64,

    /// Path to the DRM connector status sysfs file (used in "drm" mode)
    #[serde(default = "defaults::hdmi_drm_path")]
    drm_path: PathBuf,

    /// Path to the CEC device (used in "cec" mode)
    #[serde(default = "defaults::cec_device")]
    cec_device: PathBuf,
}

impl Default for HdmiConfig {
    fn default() -> Self {
        Self {
            detect: defaults::hdmi_detect(),
            timeout_secs: defaults::hdmi_timeout_secs(),
            drm_path: defaults::hdmi_drm_path(),
            cec_device: defaults::cec_device(),
        }
    }
}

#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
enum TvControlMode {
    Smartplug,
    Cec,
    Both,
    /// Does not touch the TV at all; shows a swaynag notification instead.
    DryRun,
}

#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
enum HdmiDetectMode {
    Drm,
    Timeout,
    Cec,
}

